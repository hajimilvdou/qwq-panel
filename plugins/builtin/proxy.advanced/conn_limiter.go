package main

import (
	"fmt"
	"net"
	"strings"
	"sync"
)

const (
	maxTrackedUsers = 512
	maxTrackedIPs   = 2048
)

// resolveEffectiveLimit 合并套餐默认值与单用户覆盖值（-1 继承套餐，0 表示不限制，>0 表示显式上限）。
func resolveEffectiveLimit(planLimit, userOverride int) int {
	if userOverride >= 0 {
		return userOverride
	}
	if planLimit < 0 {
		return 0
	}
	return planLimit
}

// userConnSnapshot 描述单个代理用户的实时连接数与在线 IP 数统计。
type userConnSnapshot struct {
	UserID            string `json:"user_id"`
	ActiveConnections int    `json:"active_connections"`
	ActiveIPs         int    `json:"active_ips"`
	MaxConnections    int    `json:"max_connections"`
	MaxIPs            int    `json:"max_ips"`
	RejectedTotal     uint64 `json:"rejected_total"`
}

type userConnState struct {
	activeConns int
	ipCounts    map[string]int
	rejected    uint64
}

// connLimiter 提供有界内存、线程安全的单用户并发 TCP 连接数与同时在线 IP 数实时准入控制。
type connLimiter struct {
	mu    sync.Mutex
	users map[string]*userConnState
}

func newConnLimiter() *connLimiter {
	return &connLimiter{
		users: make(map[string]*userConnState),
	}
}

func normalizeClientIP(raw string) string {
	raw = strings.TrimSpace(raw)
	if host, _, err := net.SplitHostPort(raw); err == nil {
		raw = host
	}
	if ip := net.ParseIP(raw); ip != nil {
		return ip.String()
	}
	return raw
}

// Admit 原子检查并占用指定用户的一个并发连接名额与客户端 IP 名额。
// 返回 release 回调；调用方务必在连接关闭时调用 release()。
func (l *connLimiter) Admit(userID, clientIP string, maxConns, maxIPs int) (bool, string, func()) {
	noop := func() {}
	if userID == "" {
		return true, "", noop
	}
	ip := normalizeClientIP(clientIP)
	l.mu.Lock()
	defer l.mu.Unlock()

	st, ok := l.users[userID]
	if !ok {
		if len(l.users) >= maxTrackedUsers {
			// 驱逐无活跃连接的空记录，确保 1C1G 内存有界。
			for k, v := range l.users {
				if v.activeConns == 0 {
					delete(l.users, k)
				}
			}
		}
		st = &userConnState{ipCounts: make(map[string]int)}
		l.users[userID] = st
	}

	if maxConns > 0 && st.activeConns >= maxConns {
		st.rejected++
		return false, fmt.Sprintf("并发连接数已达上限 (%d/%d)", st.activeConns, maxConns), noop
	}
	if maxIPs > 0 && ip != "" {
		if _, existingIP := st.ipCounts[ip]; !existingIP && len(st.ipCounts) >= maxIPs {
			st.rejected++
			return false, fmt.Sprintf("同时在线 IP 数已达上限 (%d/%d)", len(st.ipCounts), maxIPs), noop
		}
	}

	st.activeConns++
	if ip != "" && (len(st.ipCounts) < maxTrackedIPs || st.ipCounts[ip] > 0) {
		st.ipCounts[ip]++
	}

	var once sync.Once
	return true, "", func() {
		once.Do(func() {
			l.mu.Lock()
			defer l.mu.Unlock()
			cur, exists := l.users[userID]
			if !exists {
				return
			}
			if cur.activeConns > 0 {
				cur.activeConns--
			}
			if ip != "" {
				if c := cur.ipCounts[ip]; c <= 1 {
					delete(cur.ipCounts, ip)
				} else {
					cur.ipCounts[ip] = c - 1
				}
			}
		})
	}
}

func (l *connLimiter) SnapshotUser(userID string, maxConns, maxIPs int) userConnSnapshot {
	l.mu.Lock()
	defer l.mu.Unlock()
	out := userConnSnapshot{
		UserID:         userID,
		MaxConnections: maxConns,
		MaxIPs:         maxIPs,
	}
	if st, ok := l.users[userID]; ok {
		out.ActiveConnections = st.activeConns
		out.ActiveIPs = len(st.ipCounts)
		out.RejectedTotal = st.rejected
	}
	return out
}

// renderConnLimitNftables 生成基于每用户 traffic_mark (0x5100..0x51FF) 的内核 nftables 连接数与 IP 限制参考规则。
func renderConnLimitNftables(users []userRecord) string {
	var b strings.Builder
	b.WriteString("# Generated by qwq proxy.advanced — per-user connection & IP guard (nftables)\n")
	b.WriteString("table inet qwq_proxy_connlimit {\n")
	b.WriteString("    chain forward_guard {\n")
	b.WriteString("        type filter hook output priority 0; policy accept;\n")
	count := 0
	for _, u := range users {
		if u.Status != "active" || u.TrafficMark == 0 {
			continue
		}
		if u.EffectiveMaxConnections > 0 {
			count++
			fmt.Fprintf(&b, "        meta mark 0x%04x ct state new ct count over %d counter drop comment \"user:%s max_conns\"\n",
				u.TrafficMark, u.EffectiveMaxConnections, u.ID)
		}
	}
	if count == 0 {
		b.WriteString("        # No active users with explicit max_connections limit.\n")
	}
	b.WriteString("    }\n}\n")
	return b.String()
}
