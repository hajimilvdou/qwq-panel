// BackendProbe 诚实报告当前宿主机可用的反向代理引擎（始终具备零依赖 builtin-go 引擎）。
type BackendProbe struct {
	ActiveEngine string `json:"active_engine"`
	CaddyPath    string `json:"caddy_path,omitempty"`
	NginxPath    string `json:"nginx_path,omitempty"`
	BuiltinReady bool   `json:"builtin_ready"`
}

func detectBackends(preferred string) BackendProbe {
	caddyPath, _ := exec.LookPath("caddy")
	nginxPath, _ := exec.LookPath("nginx")
	active := "builtin-go"
	switch strings.ToLower(strings.TrimSpace(preferred)) {
	case "caddy":
		if caddyPath != "" {
			active = "caddy"
		}
	case "nginx":
		if nginxPath != "" {
			active = "nginx"
		}
	}
	return BackendProbe{
		ActiveEngine: active,
		CaddyPath:    caddyPath,
		NginxPath:    nginxPath,
		BuiltinReady: true,
	}
}

// renderCaddyfile 根据经过严格校验的站点列表生成防注入的确定性 Caddyfile。
func renderCaddyfile(sites []SiteRecord) string {
	var b strings.Builder
	b.WriteString("# Generated by qwq web.ingress — do not edit manually\n\n")
	active := 0
	for _, s := range sites {
		if !s.Enabled {
			continue
		}
		active++
		addr := s.Domain
		if s.TLSMode == "off" {
			addr = "http://" + s.Domain
		}
		fmt.Fprintf(&b, "%s {\n", addr)
		b.WriteString("    encode zstd gzip\n")
		if s.TLSMode == "custom" && s.CertID != "" {
			fmt.Fprintf(&b, "    tls /var/lib/qwq/certs/%s/fullchain.pem /var/lib/qwq/certs/%s/privkey.pem\n", s.CertID, s.CertID)
		}
		if s.HasBasicAuth {
			fmt.Fprintf(&b, "    basic_auth {\n        %s %s\n    }\n", s.BasicAuthUser, s.BasicAuthHash)
		}
		b.WriteString("    header {\n")
		b.WriteString("        X-Content-Type-Options nosniff\n")
		b.WriteString("        X-Frame-Options SAMEORIGIN\n")
		if s.TLSMode != "off" && s.ForceHTTPS {
			b.WriteString("        Strict-Transport-Security \"max-age=31536000; includeSubDomains\"\n")
		}
		keys := sortedHeaderKeys(s.ExtraHeaders)
		for _, k := range keys {
			fmt.Fprintf(&b, "        %s \"%s\"\n", k, s.ExtraHeaders[k])
		}
		b.WriteString("    }\n")
		if s.PathPrefix != "/" {
			fmt.Fprintf(&b, "    handle %s* {\n        reverse_proxy %s\n    }\n", s.PathPrefix, s.UpstreamURL)
		} else {
			fmt.Fprintf(&b, "    reverse_proxy %s\n", s.UpstreamURL)
		}
		b.WriteString("}\n\n")
	}
	if active == 0 {
		b.WriteString("# No enabled ingress sites configured.\n")
	}
	return b.String()
}

// renderNginxConfig 根据经过严格校验的站点列表生成防注入的确定性 Nginx 配置块。
func renderNginxConfig(sites []SiteRecord) string {
	var b strings.Builder
	b.WriteString("# Generated by qwq web.ingress — do not edit manually\n\n")
	active := 0
	for _, s := range sites {
		if !s.Enabled {
			continue
		}
		active++
		if s.RateLimitRPS > 0 {
			zone := strings.ReplaceAll(s.ID, "-", "_")
			fmt.Fprintf(&b, "limit_req_zone $binary_remote_addr zone=%s:2m rate=%dr/s;\n", zone, s.RateLimitRPS)
		}
		b.WriteString("server {\n")
		if s.TLSMode == "off" {
			b.WriteString("    listen 80;\n    listen [::]:80;\n")
		} else {
			b.WriteString("    listen 443 ssl http2;\n    listen [::]:443 ssl http2;\n")
			certRef := s.CertID
			if certRef == "" {
				certRef = s.Domain
			}
			fmt.Fprintf(&b, "    ssl_certificate     /var/lib/qwq/certs/%s/fullchain.pem;\n", certRef)
			fmt.Fprintf(&b, "    ssl_certificate_key /var/lib/qwq/certs/%s/privkey.pem;\n", certRef)
		}
		fmt.Fprintf(&b, "    server_name %s;\n", s.Domain)
		b.WriteString("    add_header X-Content-Type-Options nosniff always;\n")
		b.WriteString("    add_header X-Frame-Options SAMEORIGIN always;\n")
		for _, k := range sortedHeaderKeys(s.ExtraHeaders) {
			fmt.Fprintf(&b, "    add_header %s \"%s\" always;\n", k, s.ExtraHeaders[k])
		}
		fmt.Fprintf(&b, "    location %s {\n", s.PathPrefix)
		if s.RateLimitRPS > 0 {
			zone := strings.ReplaceAll(s.ID, "-", "_")
			fmt.Fprintf(&b, "        limit_req zone=%s burst=%d nodelay;\n", zone, s.RateLimitBurst)
		}
		fmt.Fprintf(&b, "        proxy_pass %s;\n", s.UpstreamURL)
		b.WriteString("        proxy_http_version 1.1;\n")
		b.WriteString("        proxy_set_header Host $host;\n")
		b.WriteString("        proxy_set_header X-Real-IP $remote_addr;\n")
		b.WriteString("        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n")
		b.WriteString("        proxy_set_header X-Forwarded-Proto $scheme;\n")
		if s.WebSocket {
			b.WriteString("        proxy_set_header Upgrade $http_upgrade;\n")
			b.WriteString("        proxy_set_header Connection \"upgrade\";\n")
		}
		b.WriteString("    }\n}\n\n")
	}
	if active == 0 {
		b.WriteString("# No enabled ingress sites configured.\n")
	}
	return b.String()
}

func sortedHeaderKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func atomicWriteFile(path string, content []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, content, 0o640); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return nil
}
